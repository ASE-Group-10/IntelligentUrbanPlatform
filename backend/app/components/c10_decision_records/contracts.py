class DecisionIdSelector(Model):
    """Select one decision by ID. C12 replay also sends its ``runId``; C10 then
    answers NotFound (``C10.DECISION_NOT_FOUND``) unless the decision was
    recorded in that run, so a replay can never read another run's decisions."""

    decision_id: UUID
    run_id: UUID | None = None


class SubjectSelector(Model):
    subject_type: SubjectType
    subject_id: UUID
    subject_version: int | None = None
    run_id: UUID | None = None


DecisionSelector = DecisionIdSelector | SubjectSelector


