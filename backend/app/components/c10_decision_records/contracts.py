class DecisionRecord(Model):
    """One planning/allocation decision with the evidence used, including
    attempts that selected nothing. All evidence snapshots must come from one
    corpus version, equal to ``inputVersions.corpusVersion`` (null when no
    knowledge was used); if the corpus changes between queries, re-query."""

    decision_id: UUID  # generated by the caller
    idempotency_key: str = Field(min_length=1)
    decision_type: DecisionType
    producer: Literal["C05", "C08"]
    decided_by: str
    subject: Subject
    attempt_outcome: AttemptOutcome
    related_decision_id: UUID | None
    input_versions: InputVersions
    selected_option: SelectedOption | None  # only for Selected
    considered_alternatives: list[Alternative]
    reasons: list[Reason] = Field(min_length=1)
    predicted_effects: PredictedEffects | None = None
    evidence_snapshots: list[EvidenceSnapshot]
    limitations: list[str]
    run_scope: RunScope
    decided_at: datetime

    @model_validator(mode="after")
    def _refs_resolve(self):
        stored = {p.passage_id for s in self.evidence_snapshots for p in s.items}
        cited = {
            r
            for x in [*self.reasons, *self.considered_alternatives]
            for r in x.evidence_ref_ids
        }
        missing = cited - stored
        if missing:
            raise ValueError(f"C10.EVIDENCE_REF_MISSING: {sorted(map(str, missing))}")
        if (
            self.decision_type is DecisionType.REPLAN
            and self.related_decision_id is None
        ):
            raise ValueError("Replan requires relatedDecisionId")
        selected = self.attempt_outcome is AttemptOutcome.SELECTED
        if selected != (self.selected_option is not None):
            raise ValueError("selectedOption is required for Selected and only then")
        if selected and self.subject.version is None:
            raise ValueError("a Selected decision needs the saved subject version")
        if (self.subject.type is SubjectType.PLANNING_ATTEMPT) and (
            selected or self.subject.version is not None
        ):
            raise ValueError("PlanningAttempt has no version and cannot be Selected")
        versions = {s.corpus_version for s in self.evidence_snapshots}
        expected = {self.input_versions.corpus_version} - {None}
        if versions != expected:
            raise ValueError(
                "evidenceSnapshots must all use inputVersions.corpusVersion "
                "(null when there are no snapshots)"
            )
        if selected and any(
            s.rule_coverage is RuleCoverage.INCOMPLETE for s in self.evidence_snapshots
        ):
            raise ValueError(
                "cannot select with incomplete rule coverage; record "
                "DataUnavailable (UC03) or ReviewRequired (UC07)"
            )
        return self


