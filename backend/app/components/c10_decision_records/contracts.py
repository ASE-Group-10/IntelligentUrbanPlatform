# ---- DecisionRecord / recordDecision ----
class DecisionType(StrEnum):
    PLAN_GENERATED = "PlanGenerated"
    REPLAN = "Replan"
    ALLOCATION = "Allocation"
    NEGOTIATION = "Negotiation"


class SubjectType(StrEnum):
    PLAN = "Plan"
    ALLOCATION = "Allocation"
    NEGOTIATION = "Negotiation"
    PLANNING_ATTEMPT = "PlanningAttempt"  # no plan exists yet (failed UC03)


class Subject(Model):
    """What the decision is about. ``version`` is null when no saved version
    exists: always for ``PlanningAttempt``, never for a ``Selected`` outcome."""

    type: SubjectType
    id: UUID
    version: int | None = Field(ge=1)


class AttemptOutcome(StrEnum):
    """Result of the planning/allocation attempt this record explains."""

    SELECTED = "Selected"  # an option was chosen and saved
    INFEASIBLE = "Infeasible"  # no feasible plan or revision
    DATA_UNAVAILABLE = "DataUnavailable"  # UC03: required inputs/rules unreliable
    NO_CHANGE = "NoChange"  # UC07: current plan still valid
    REVIEW_REQUIRED = "ReviewRequired"  # UC07: cannot decide safely, no revision


