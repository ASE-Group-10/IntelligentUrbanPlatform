-- migrate:up
create schema c05_planning;

-- One immutable snapshot per version. Indexed identifiers come from the same
-- contract JSON that the operator reads. Later versions keep earlier reads valid.
create table c05_planning.plan_versions (
    scope_key text generated always as (
        case
            when proposal #>> '{runScope,scope}' = 'live'
                 and proposal #>> '{runScope,runId}' is null then 'live'
            when proposal #>> '{runScope,scope}' = 'simulation'
                then 'simulation:' || (proposal #>> '{runScope,runId}')::uuid::text
        end
    ) stored,
    proposal jsonb not null,
    plan_id uuid generated always as ((proposal ->> 'planId')::uuid) stored,
    version integer generated always as ((proposal ->> 'version')::integer) stored,
    decision_id uuid generated always as ((proposal ->> 'decisionId')::uuid) stored not null,
    correlation_id uuid not null,
    planned_departure_at timestamptz not null,
    primary key (scope_key, plan_id, version),
    check (version >= 1)
);

create function c05_planning.reject_version_change() returns trigger
    language plpgsql as $$
begin
    raise exception 'c05_planning.plan_versions is insert-only';
end;
$$;

create trigger plan_versions_insert_only before update or delete
    on c05_planning.plan_versions for each row
    execute function c05_planning.reject_version_change();

-- A retry returns the version generated by the original command, even if an
-- operator has since confirmed it or C07 has requested a revision.
create table c05_planning.generation_receipts (
    scope_key text not null,
    principal_id text not null,
    idempotency_key text not null,
    request_body jsonb not null,
    plan_id uuid not null,
    version integer not null,
    primary key (scope_key, principal_id, idempotency_key),
    foreign key (scope_key, plan_id, version)
        references c05_planning.plan_versions (scope_key, plan_id, version)
);

-- Confirming or revising a plan can queue one PlanReady for that saved version.
-- Generating the initial proposal leaves this table untouched.
create table c05_planning.outbox (
    seq bigint generated always as identity,
    event_id uuid primary key,
    scope_key text not null,
    plan_id uuid not null,
    version integer not null,
    event_type text not null,
    envelope jsonb not null,
    created_at timestamptz not null default now(),
    published_at timestamptz,
    unique (scope_key, plan_id, version, event_type),
    foreign key (scope_key, plan_id, version)
        references c05_planning.plan_versions (scope_key, plan_id, version)
);

create index outbox_unpublished on c05_planning.outbox (seq) where published_at is null;

